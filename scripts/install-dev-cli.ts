/**
 * Installs a `relay` launcher so this checkout's CLI can be run from any
 * project directory — a stand-in for a global install while the project is
 * source-only. The launcher rebuilds the CLI bundle, points `RELAY_ENV_ROOT`
 * at this checkout (so secrets load outside the repo), and forwards every
 * argument to the CLI.
 *
 * Usage:
 *   pnpm relay:install                     # writes ~/.local/bin/relay
 *   pnpm relay:uninstall                   # removes it
 *   RELAY_BIN_DIR=... pnpm relay:install   # override the bin directory
 */

import { chmodSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { delimiter, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repo = resolve(fileURLToPath(new URL("..", import.meta.url)));
const binDir = process.env.RELAY_BIN_DIR?.trim() || join(homedir(), ".local", "bin");
const target = join(binDir, "relay");

if (process.argv.includes("--uninstall")) {
	rmSync(target, { force: true });
	console.log(`Removed ${target}`);
	process.exit(0);
}

if (process.platform === "win32") {
	console.error("The dev launcher is a bash script; use `pnpm relay` from the repo on Windows.");
	process.exit(1);
}

/** Single-quote for the generated bash script. */
const quote = (value: string) => `'${value.replaceAll("'", "'\\''")}'`;

const launcher = `#!/usr/bin/env bash
# Generated by \`pnpm relay:install\` from ${repo}.
# Runs this checkout's relay CLI in the caller's directory (rebuilding the
# bundle first) with the checkout's env files loaded via RELAY_ENV_ROOT.
set -euo pipefail
REPO=${quote(repo)}
export RELAY_ENV_ROOT="$REPO"
"$REPO/node_modules/.bin/vp" -C "$REPO/packages/cli" pack >/dev/null
exec node "$REPO/scripts/run-env.ts" "$REPO/packages/cli/dist/index.mjs" "$@"
`;

mkdirSync(binDir, { recursive: true });
writeFileSync(target, launcher, { mode: 0o755 });
chmodSync(target, 0o755);
console.log(`Installed ${target}`);

const pathEntries = (process.env.PATH ?? "").split(delimiter);
if (!pathEntries.includes(binDir)) {
	console.log(`Note: ${binDir} is not on your PATH; add it before using \`relay\` directly.`);
}
